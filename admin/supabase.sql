-- Só o e-mail da cliente pode alterar dados e imagens
create or replace function public.eh_admin() returns boolean
language sql stable as $$
  select coalesce((auth.jwt() ->> 'email') = 'nocadoces@gmail.com', false);  -- <== TROQUE AQUI
$$;

-- ---------- Tabelas ----------
create table if not exists public.categorias (
  slug       text primary key,          -- classicos, especiais, trufas, barras
  titulo     text not null,
  info       text,                      -- texto sob o título quando não há preço de atacado
  preco_base numeric,                   -- preço da unidade (usado no texto de atacado)
  granel     numeric,                   -- preço por unidade a partir de 50 (atacado)
  unidades   text,                      -- opções de quantidade, ex.: '1,2,3' (vazio = 10,25,50,100)
  passo      int,                       -- passo do carrinho (vazio = 5)
  ordem      int default 0
);

create table if not exists public.produtos (
  id         bigint generated by default as identity primary key,
  categoria  text not null references public.categorias(slug) on update cascade on delete cascade,
  nome       text not null,
  descricao  text,
  preco      numeric not null check (preco >= 0),          -- preço normal ("de")
  preco_promo numeric check (preco_promo >= 0),            -- preço promocional ("por"); vazio = sem promoção
  destaque   boolean not null default false,
  ativo      boolean not null default true,
  ordem      int not null default 0,
  pedido     text                       -- texto enviado no WhatsApp (vazio = "Nome (descrição)")
);

create table if not exists public.promo (
  id          int primary key default 1 check (id = 1),
  ativo       boolean not null default false,
  titulo      text,
  texto       text,
  botao_texto text,
  botao_link  text,
  imagem_url  text,
  inicio      date,
  fim         date
);

-- ---------- Atualização de bancos antigos ----------
-- "create table if not exists" não adiciona colunas a tabelas que já existem.
-- Estas linhas garantem que as colunas novas existam (não mexem em nada que já está lá).
-- Ao criar uma coluna nova no futuro, acrescente aqui uma linha "add column if not exists".
alter table public.categorias add column if not exists unidades    text;
alter table public.categorias add column if not exists passo       int;
alter table public.produtos   add column if not exists preco_promo numeric check (preco_promo >= 0);
alter table public.produtos   add column if not exists destaque    boolean not null default false;
alter table public.produtos   add column if not exists pedido      text;

-- ---------- Segurança (RLS): todos leem, só a cliente escreve ----------
alter table public.categorias enable row level security;
alter table public.produtos   enable row level security;
alter table public.promo      enable row level security;

drop policy if exists "leitura publica" on public.categorias;
create policy "leitura publica" on public.categorias for select using (true);
drop policy if exists "leitura publica" on public.produtos;
create policy "leitura publica" on public.produtos   for select using (true);
drop policy if exists "leitura publica" on public.promo;
create policy "leitura publica" on public.promo      for select using (true);

drop policy if exists "admin escreve" on public.categorias;
create policy "admin escreve" on public.categorias for all using (public.eh_admin()) with check (public.eh_admin());
drop policy if exists "admin escreve" on public.produtos;
create policy "admin escreve" on public.produtos   for all using (public.eh_admin()) with check (public.eh_admin());
drop policy if exists "admin escreve" on public.promo;
create policy "admin escreve" on public.promo      for all using (public.eh_admin()) with check (public.eh_admin());

-- ---------- Feedbacks de clientes ----------
create table if not exists public.feedbacks (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  ocasiao    text,                                  -- ex.: Aniversário, Presente
  texto      text not null,                         -- comentário do cliente
  estrelas   int not null default 5 check (estrelas between 1 and 5),
  foto_url   text,                                  -- vazio = mostra a inicial do nome
  ativo      boolean not null default true,
  ordem      int not null default 0
);

alter table public.feedbacks enable row level security;
drop policy if exists "leitura publica" on public.feedbacks;
create policy "leitura publica" on public.feedbacks for select using (true);
drop policy if exists "admin escreve" on public.feedbacks;
create policy "admin escreve"   on public.feedbacks for all using (public.eh_admin()) with check (public.eh_admin());

-- ---------- Imagens (banner e fotos de feedbacks) ----------
insert into storage.buckets (id, name, public) values ('imagens', 'imagens', true) on conflict (id) do nothing;
drop policy if exists "imagens leitura publica" on storage.objects;
create policy "imagens leitura publica" on storage.objects for select using (bucket_id = 'imagens');
drop policy if exists "imagens admin escreve" on storage.objects;
create policy "imagens admin escreve" on storage.objects for all
  using (bucket_id = 'imagens' and public.eh_admin())
  with check (bucket_id = 'imagens' and public.eh_admin());

