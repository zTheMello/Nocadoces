drop policy if exists "leitura publica" on public.categorias;
create policy "leitura publica" on public.categorias for select using (true);
drop policy if exists "leitura publica" on public.produtos;
create policy "leitura publica" on public.produtos   for select using (true);
drop policy if exists "leitura publica" on public.promo;
create policy "leitura publica" on public.promo      for select using (true);

drop policy if exists "admin escreve" on public.categorias;
create policy "admin escreve" on public.categorias for all using (public.eh_admin()) with check (public.eh_admin());
drop policy if exists "admin escreve" on public.produtos;
create policy "admin escreve" on public.produtos   for all using (public.eh_admin()) with check (public.eh_admin());
drop policy if exists "admin escreve" on public.promo;
create policy "admin escreve" on public.promo      for all using (public.eh_admin()) with check (public.eh_admin());

