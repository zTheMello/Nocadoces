create table if not exists public.pedidos (
  id            bigint generated by default as identity primary key,
  criado_em     timestamptz not null default now(),
  cliente_nome  text check (char_length(cliente_nome) <= 80),
  data_desejada date,
  itens         jsonb not null default '[]'::jsonb,   -- [{nome, qtd, obs, subtotal}]
  total         numeric not null default 0 check (total >= 0 and total <= 100000),
  status        text not null default 'novo' check (status in ('novo','confirmado','producao','pronto','entregue','cancelado')),
  pago          boolean not null default false,
  origem        text not null default 'site'
);

create table if not exists public.estoque (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  unidade    text,
  quantidade numeric not null default 0 check (quantidade >= 0),
  minimo     numeric not null default 0 check (minimo >= 0)
);

create table if not exists public.financeiro (
  id        bigint generated by default as identity primary key,
  data      date not null default current_date,
  tipo      text not null check (tipo in ('entrada','saida')),
  categoria text,
  descricao text not null,
  valor     numeric not null check (valor > 0),
  pedido_id bigint references public.pedidos(id) on delete cascade   -- entrada criada ao marcar o pedido como pago
);
create unique index if not exists financeiro_pedido_uniq on public.financeiro (pedido_id) where pedido_id is not null;

create table if not exists public.configuracoes (
  id       int primary key default 1 check (id = 1),
  whatsapp text check (whatsapp ~ '^[0-9]{12,13}$')
);
