-- Só o e-mail da cliente pode alterar dados e imagens
create or replace function public.eh_admin() returns boolean
language sql stable as $$
  select coalesce((auth.jwt() ->> 'email') = 'nocadoces@gmail.com', false);  -- e-mail do admin (o mesmo usuário criado em Authentication > Users)
$$;

-- ---------- Tabelas ----------
create table if not exists public.categorias (
  slug       text primary key,          -- classicos, especiais, trufas, barras
  titulo     text not null,
  info       text,                      -- texto sob o título quando não há preço de atacado
  preco_base numeric,                   -- preço da unidade (usado no texto de atacado)
  granel     numeric,                   -- preço por unidade a partir de 50 (atacado)
  unidades   text,                      -- opções de quantidade, ex.: '1,2,3' (vazio = 10,25,50,100)
  passo      int,                       -- passo do carrinho (vazio = 5)
  ordem      int default 0
);

create table if not exists public.produtos (
  id         bigint generated by default as identity primary key,
  categoria  text not null references public.categorias(slug) on update cascade on delete cascade,
  nome       text not null,
  descricao  text,
  preco      numeric not null check (preco >= 0),          -- preço normal ("de")
  preco_promo numeric check (preco_promo >= 0),            -- preço promocional ("por"); vazio = sem promoção
  destaque   boolean not null default false,
  ativo      boolean not null default true,
  ordem      int not null default 0,
  pedido     text                       -- texto enviado no WhatsApp (vazio = "Nome (descrição)")
);

create table if not exists public.promo (
  id          int primary key default 1 check (id = 1),
  ativo       boolean not null default false,
  titulo      text,
  texto       text,
  botao_texto text,
  botao_link  text,
  imagem_url  text,
  inicio      date,
  fim         date
);

-- ---------- Atualização de bancos antigos ----------
-- "create table if not exists" não adiciona colunas a tabelas que já existem.
-- Estas linhas garantem que as colunas novas existam (não mexem em nada que já está lá).
-- Ao criar uma coluna nova no futuro, acrescente aqui uma linha "add column if not exists".
