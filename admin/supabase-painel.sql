create table if not exists public.pedidos (
  id            bigint generated by default as identity primary key,
  criado_em     timestamptz not null default now(),
  cliente_nome  text check (char_length(cliente_nome) <= 80),
  data_desejada date,
  itens         jsonb not null default '[]'::jsonb,   -- [{nome, qtd, obs, subtotal}]
  total         numeric not null default 0 check (total >= 0 and total <= 100000),
  status        text not null default 'novo' check (status in ('novo','confirmado','producao','pronto','entregue','cancelado')),
  pago          boolean not null default false,
  origem        text not null default 'site'
);

create table if not exists public.estoque (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  unidade    text,
  quantidade numeric not null default 0 check (quantidade >= 0),
  minimo     numeric not null default 0 check (minimo >= 0)
);

create table if not exists public.financeiro (
  id        bigint generated by default as identity primary key,
  data      date not null default current_date,
  tipo      text not null check (tipo in ('entrada','saida')),
  categoria text,
  descricao text not null,
  valor     numeric not null check (valor > 0),
  pedido_id bigint references public.pedidos(id) on delete cascade   -- entrada criada ao marcar o pedido como pago
);
create unique index if not exists financeiro_pedido_uniq on public.financeiro (pedido_id) where pedido_id is not null;

create table if not exists public.configuracoes (
  id       int primary key default 1 check (id = 1),
  whatsapp text check (whatsapp ~ '^[0-9]{12,13}$')
);
insert into public.configuracoes (id, whatsapp) values (1, '5583991839139') on conflict (id) do nothing;

-- ---------- Segurança (RLS) ----------
alter table public.pedidos       enable row level security;
alter table public.estoque       enable row level security;
alter table public.financeiro    enable row level security;
alter table public.configuracoes enable row level security;

-- o carrinho do site (visitante) só pode CRIAR pedido novo e não pago; não consegue ler nem alterar nada
drop policy if exists "site cria pedido" on public.pedidos;
create policy "site cria pedido" on public.pedidos for insert to anon, authenticated
  with check (status = 'novo' and pago = false and origem = 'site'
              and jsonb_typeof(itens) = 'array' and jsonb_array_length(itens) between 1 and 60);

drop policy if exists "admin gerencia" on public.pedidos;
create policy "admin gerencia" on public.pedidos    for all using (public.eh_admin()) with check (public.eh_admin());
drop policy if exists "admin gerencia" on public.estoque;
create policy "admin gerencia" on public.estoque    for all using (public.eh_admin()) with check (public.eh_admin());
drop policy if exists "admin gerencia" on public.financeiro;
create policy "admin gerencia" on public.financeiro for all using (public.eh_admin()) with check (public.eh_admin());

drop policy if exists "leitura publica" on public.configuracoes;
create policy "leitura publica" on public.configuracoes for select using (true);
drop policy if exists "admin escreve" on public.configuracoes;
create policy "admin escreve" on public.configuracoes for all using (public.eh_admin()) with check (public.eh_admin());

-- permissões da API (necessárias em projetos novos do Supabase; não abrem nada além das regras acima)
grant insert on public.pedidos to anon;
grant select on public.configuracoes to anon;
grant select, insert, update, delete on public.pedidos, public.estoque, public.financeiro, public.configuracoes to authenticated;

