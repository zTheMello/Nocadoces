-- ---------- Feedbacks de clientes ----------
create table if not exists public.feedbacks (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  ocasiao    text,                                  -- ex.: Aniversário, Presente
  texto      text not null,                         -- comentário do cliente
  estrelas   int not null default 5 check (estrelas between 1 and 5),
  foto_url   text,                                  -- vazio = mostra a inicial do nome
  ativo      boolean not null default true,
  ordem      int not null default 0
);

alter table public.feedbacks enable row level security;
create policy "leitura publica" on public.feedbacks for select using (true);
create policy "admin escreve"   on public.feedbacks for all using (public.eh_admin()) with check (public.eh_admin());
